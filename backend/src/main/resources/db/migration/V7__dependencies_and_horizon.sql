CREATE TABLE task_dependencies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    owner_id BIGINT NOT NULL,
    blocked_task_id BIGINT NOT NULL,
    blocker_task_id BIGINT NOT NULL,
    CONSTRAINT pk_task_dependencies PRIMARY KEY (id),
    CONSTRAINT uk_task_dependencies_blocked_blocker UNIQUE (blocked_task_id, blocker_task_id),
    CONSTRAINT ck_task_dependencies_distinct_tasks CHECK (blocked_task_id <> blocker_task_id),
    CONSTRAINT fk_task_dependencies_owner FOREIGN KEY (owner_id) REFERENCES users (id),
    CONSTRAINT fk_task_dependencies_blocked_task
        FOREIGN KEY (blocked_task_id) REFERENCES tasks (id) ON DELETE CASCADE,
    CONSTRAINT fk_task_dependencies_blocker_task
        FOREIGN KEY (blocker_task_id) REFERENCES tasks (id) ON DELETE CASCADE
);

CREATE INDEX idx_task_dependencies_owner_id ON task_dependencies (owner_id);

CREATE TABLE daily_plan_revision_dependencies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    revision_id BIGINT NOT NULL,
    blocked_source_task_id BIGINT NOT NULL,
    blocker_source_task_id BIGINT NOT NULL,
    CONSTRAINT pk_daily_plan_revision_dependencies PRIMARY KEY (id),
    CONSTRAINT uk_daily_plan_revision_dependencies_revision_pair
        UNIQUE (revision_id, blocked_source_task_id, blocker_source_task_id),
    CONSTRAINT fk_daily_plan_revision_dependencies_revision
        FOREIGN KEY (revision_id) REFERENCES daily_plan_revisions (id) ON DELETE CASCADE
);

CREATE INDEX idx_daily_plan_revision_dependencies_revision_id
    ON daily_plan_revision_dependencies (revision_id);

