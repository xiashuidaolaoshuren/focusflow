const fieldVariants = cva(
  "group/field flex w-full gap-2 data-[invalid=true]:text-destructive",
  {
    variants: {
      orientation: {
        vertical: "flex-col *:w-full [&>.sr-only]:w-auto",
        horizontal:
          "flex-row items-center has-[>[data-slot=field-content]]:items-start *:data-[slot=field-label]:flex-auto has-[>[data-slot=field-content]]:[&>[role=checkbox],[role=radio]]:mt-px",
        responsive:
          "flex-col *:w-full @md/field-group:flex-row @md/field-group:items-center @md/field-group:*:w-auto @md/field-group:has-[>[data-slot=field-content]]:items-start @md/field-group:*:data-[slot=field-label]:flex-auto [&>.sr-only]:w-auto @md/field-group:has-[>[data-slot=field-content]]:[&>[role=checkbox],[role=radio]]:mt-px",
      },
    },
    defaultVariants: {
      orientation: "vertical",
    },
  }
)

type FieldControlProps = {
  id: string
  'aria-invalid'?: boolean
  'aria-describedby'?: string
}

type FieldProps = Omit<React.ComponentProps<"div">, "children"> &
  VariantProps<typeof fieldVariants> & {
    label?: ReactNode
    name?: string
    required?: boolean
    error?: string | undefined
    apiError?: unknown
    description?: ReactNode
    id?: string
    children?: ReactNode | ((control: FieldControlProps) => ReactNode)
  }

function Field({
  className,
  orientation = "vertical",
  label,
  name,
  required = false,
  error,
  apiError,
  description,
  id: idProp,
  children,
  ...props
}: FieldProps) {
  const generatedId = useId()
  const controlId = idProp ?? `${generatedId}-control`
  const apiMessage = name ? getFieldError(apiError, name) : undefined
  const message = error ?? apiMessage
  const errorId = message ? `${controlId}-error` : undefined
  const useEnhancedChrome =
    label != null ||
    name != null ||
    error != null ||
    apiError != null ||
    description != null ||
    typeof children === "function"

  if (!useEnhancedChrome) {
    return (
      <div
        role="group"
        data-slot="field"
        data-orientation={orientation}
        className={cn(fieldVariants({ orientation }), className)}
        {...props}
      >
        {children as ReactNode}
      </div>
    )
  }

  const controlProps: FieldControlProps = {
    id: controlId,
    ...(message && errorId
      ? { "aria-invalid": true as const, "aria-describedby": errorId }
      : {}),
  }

  const control =
    typeof children === "function" ? children(controlProps) : children

  return (
    <div
      role="group"
      data-slot="field"
      data-orientation={orientation}
      data-invalid={message ? true : undefined}
      className={cn(fieldVariants({ orientation }), className)}
      {...props}
    >
      {label != null ? (
        <FieldLabel htmlFor={controlId}>
          {label}
          {required ? (
            <span className="ml-0.5 text-destructive" aria-hidden="true">
              *
            </span>
          ) : null}
        </FieldLabel>
      ) : null}
      {control}
      {description != null ? (
        <FieldDescription>{description}</FieldDescription>
      ) : null}
      {message != null ? <FieldError id={errorId}>{message}</FieldError> : null}
    </div>
  )
}

